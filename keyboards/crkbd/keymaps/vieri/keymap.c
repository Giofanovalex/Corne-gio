void render_slave(void) {
    // WPM label
    oled_set_cursor(0, 6);
    oled_write_P(PSTR("wpm  "), false);

    // Angka WPM — snprintf aman di semua versi QMK
    char wpm_str[4];
    snprintf(wpm_str, sizeof(wpm_str), "%3d", get_current_wpm());
    oled_set_cursor(0, 7);
    oled_write(wpm_str, false);
}

